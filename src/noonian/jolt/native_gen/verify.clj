(ns noonian.jolt.native-gen.verify
  "A C probe whose constants are the sizeof, alignment and every scalar field
  offset of each generated record, folded by clang, so the layouts jolt
  computes can be checked against the compiler's for each target."
  (:require [noonian.jolt.native-gen.clang :as clang]
            [noonian.jolt.native-gen.ast :as ast]
            [noonian.jolt.native-gen.types :as types]
            [clojure.string :as str]
            [clojure.java.io :as io]))

(defn- scalar-paths
  "[[path-segments ...] ...] for the scalars of a descriptor, entering nested
  structs and unions but stopping at arrays."
  ([desc] (scalar-paths desc []))
  ([[_ fields] prefix]
   (mapcat (fn [[name t]]
             (cond
               (keyword? t) [(conj prefix (clojure.core/name name))]
               (#{:struct :union} (first t)) (scalar-paths t (conj prefix (clojure.core/name name)))
               :else [(conj prefix (clojure.core/name name))]))
           fields)))

(defn- c-spelling
  "How C names a record: with its tag, since a typedef of the same name is
  only a convention, unless a typedef is the one name it has."
  [{:keys [name kind typedef-named?]}]
  (if typedef-named? name (str (clojure.core/name kind) " " name)))

(defn probe-source
  "One enum per record, named by its index: its size, its alignment, then the
  offset of each path, as constants for clang to fold."
  [headers records paths]
  (str (str/join "\n" (map #(str "#include <" % ">") headers)) "\n"
       (str/join "\n"
                 (map-indexed
                  (fn [i r]
                    (let [e (str clang/probe-prefix i)
                          c (c-spelling r)]
                      (str "enum " e " { " e "_size = sizeof(" c "), " e "_align = _Alignof(" c ")"
                           (str/join (map-indexed (fn [j path]
                                                    (str ", " e "_f" j " = __builtin_offsetof(" c ", " (str/join "." path) ")"))
                                                  (nth paths i)))
                           " };")))
                  records))
       "\n"))

(defn measure
  "Have clang fold the probe; nothing is compiled or run, so the layouts are
  those of the target clang is parsing for. Returns {record-name {:size+align
  [s a] :fields {\"a.b\" off}}}."
  [{:keys [headers work-dir] :as manifest} ctx records]
  (if (empty? records)
    {}
    (let [c-file (str (io/file work-dir "layout_probe.c"))
          records (vec records)
          paths (mapv #(scalar-paths (types/record-descriptor ctx %)) records)
          _ (spit c-file (probe-source headers records paths))
          {:keys [decls errors]} (clang/probe-ast manifest c-file)
          index (zipmap (map #(str clang/probe-prefix %) (range)) (range (count records)))]
      (when (seq errors)
        (throw (ex-info "layout probe failed to parse" {:errors errors :file c-file})))
      (into {}
            (keep (fn [d]
                    (when-let [i (index (get d "name"))]
                      (let [[size align & offsets] (map #(Long/parseLong %) (ast/enum-values d))]
                        [(:name (nth records i))
                         (cond-> {:size+align [size align]}
                           (seq offsets) (assoc :fields (zipmap (map #(str/join "." %) (nth paths i)) offsets)))]))))
            decls))))

(defn- sorted [x]
  (if (map? x) (into (sorted-map) (map (fn [[k v]] [k (sorted v)])) x) x))

(defn test-source
  "A clojure.test namespace that checks every generated layout against the
  compiler's measurements, {target {record measurement}}, which are embedded
  so the test runs from any working directory. A binding with several targets
  checks the one it is loaded as, and fails when nothing was measured for it."
  [test-ns layouts ns->records]
  (let [aliases (map-indexed (fn [i ns-sym] [ns-sym (symbol (str "r" i))]) (sort (keys ns->records)))
        alias-of (into {} aliases)
        several? (< 1 (count layouts))]
    (str "(ns " test-ns "\n"
         "  \"Generated by native-gen. Checks jolt's struct layouts against the C compiler's.\"\n"
         "  (:require [clojure.test :refer [deftest is]]\n"
         "            [clojure.string :as str]\n"
         "            [jolt.ffi :as ffi]\n"
         (str/join "\n" (map (fn [[ns-sym a]] (str "            [" ns-sym " :as " a "]")) aliases))
         "))\n\n"
         (if several?
           (str "(def measured\n  \"What the compiler measured, by target.\"\n  " (pr-str (sorted layouts)) ")\n\n"
                "(def expected\n  (get measured " (alias-of (first (sort (keys ns->records)))) "/native-gen-target))\n\n"
                ;; a record some other target defines has no measurement here
                "(defn- check [name layout-var]\n"
                "  (when-let [{:keys [size+align fields]} (get expected name)]\n"
                "    (let [layout @layout-var]\n"
                "      (is (= size+align [(ffi/sizeof layout) (ffi/alignof layout)]) (str name \" size/align\"))\n"
                "      (doseq [[path off] fields]\n"
                "        (is (= off (ffi/field-offset layout (mapv keyword (str/split path #\"\\.\"))))\n"
                "            (str name \".\" path))))))\n\n")
           (str "(def expected\n  " (pr-str (sorted (val (first layouts)))) ")\n\n"
                "(defn- check [name layout]\n"
                "  (let [{:keys [size+align fields]} (get expected name)]\n"
                "    (is (some? size+align) (str name \": no measurement\"))\n"
                "    (is (= size+align [(ffi/sizeof layout) (ffi/alignof layout)]) (str name \" size/align\"))\n"
                "    (doseq [[path off] fields]\n"
                "      (is (= off (ffi/field-offset layout (mapv keyword (str/split path #\"\\.\"))))\n"
                "          (str name \".\" path)))))\n\n"))
         "(deftest layouts-match-the-c-compiler\n"
         (when several?
           "  (is (some? expected) \"no layouts were measured for this target\")\n")
         (str/join "\n"
                   (for [[ns-sym records] (sort-by key ns->records)
                         r records]
                     (str "  (check " (pr-str r) " " (when several? "#'") (alias-of ns-sym) "/" r ")")))
         ")\n")))
