(ns native-gen.verify
  "A C probe that prints sizeof, alignment and every scalar field offset of
  each generated record, so the layouts jolt computes can be checked against
  the compiler's on each platform."
  (:require [native-gen.clang :as clang]
            [native-gen.types :as types]
            [clojure.string :as str]
            [clojure.java.io :as io]))

(defn- scalar-paths
  "[[path-segments ...] ...] for the scalars of a descriptor, entering nested
  structs and unions but stopping at arrays."
  ([desc] (scalar-paths desc []))
  ([[_ fields] prefix]
   (mapcat (fn [[name t]]
             (cond
               (keyword? t) [(conj prefix (clojure.core/name name))]
               (#{:struct :union} (first t)) (scalar-paths t (conj prefix (clojure.core/name name)))
               :else [(conj prefix (clojure.core/name name))]))
           fields)))

(defn probe-source [headers ctx records]
  (str (str/join "\n" (map #(str "#include <" % ">") headers))
       "\n#include <stdio.h>\n#include <stddef.h>\nint main(void) {\n"
       (str/join "\n"
                 (for [r records
                       :let [desc (types/record-descriptor ctx r)
                             n (:name r)]
                       line (cons (str "  printf(\"R " n " %zu %zu\\n\", sizeof(" n "), _Alignof(" n "));")
                                  (for [path (scalar-paths desc)]
                                    (str "  printf(\"F " n " " (str/join "." path) " %zu\\n\", offsetof(" n ", "
                                         (str/join "." path) "));")))]
                   line))
       "\n  return 0;\n}\n"))

(defn- parse [out]
  (reduce (fn [m line]
            (let [[k & xs] (str/split line #" ")]
              (case k
                "R" (let [[n size align] xs]
                      (assoc-in m [n :size+align] [(Long/parseLong size) (Long/parseLong align)]))
                "F" (let [[n path off] xs]
                      (assoc-in m [n :fields path] (Long/parseLong off)))
                m)))
          {} (str/split-lines out)))

(defn measure
  "Run the probe. Returns {record-name {:size+align [s a] :fields {\"a.b\" off}}}."
  [{:keys [headers work-dir] :as manifest} ctx records]
  (let [c-file (str (io/file work-dir "layout_probe.c"))
        bin (str (io/file work-dir "layout_probe"))]
    (spit c-file (probe-source headers ctx records))
    (parse (clang/compile-and-run manifest c-file bin))))

(defn test-source
  "A clojure.test namespace that checks every generated layout against the
  compiler's measurements, which are embedded so the test runs from any
  working directory."
  [test-ns measured ns->records]
  (let [aliases (map-indexed (fn [i ns-sym] [ns-sym (symbol (str "r" i))]) (sort (keys ns->records)))
        alias-of (into {} aliases)]
    (str "(ns " test-ns "\n"
         "  \"Generated by native-gen. Checks jolt's struct layouts against the C compiler's.\"\n"
         "  (:require [clojure.test :refer [deftest is]]\n"
         "            [clojure.string :as str]\n"
         "            [jolt.ffi :as ffi]\n"
         (str/join "\n" (map (fn [[ns-sym a]] (str "            [" ns-sym " :as " a "]")) aliases))
         "))\n\n"
         "(def expected\n  " (pr-str measured) ")\n\n"
         "(defn- check [name layout]\n"
         "  (let [{:keys [size+align fields]} (get expected name)]\n"
         "    (is (some? size+align) (str name \": no measurement\"))\n"
         "    (is (= size+align [(ffi/sizeof layout) (ffi/alignof layout)]) (str name \" size/align\"))\n"
         "    (doseq [[path off] fields]\n"
         "      (is (= off (ffi/field-offset layout (mapv keyword (str/split path #\"\\.\"))))\n"
         "          (str name \".\" path)))))\n\n"
         "(deftest layouts-match-the-c-compiler\n"
         (str/join "\n"
                   (for [[ns-sym records] (sort-by key ns->records)
                         r records]
                     (str "  (check " (pr-str (:name r)) " " (alias-of ns-sym) "/" (:name r) ")")))
         ")\n")))
