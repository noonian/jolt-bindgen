(ns native-gen.emit-test
  (:require [clojure.test :refer [deftest is testing]]
            [clojure.string :as str]
            [native-gen.emit :as emit]))

(deftest header-namespaces
  (is (= "sdl3.ffi.video" (emit/header-ns {:ns-prefix "sdl3.ffi" :strip-prefix "SDL_"} "/x/SDL3/SDL_video.h")))
  (is (= "sdl3.ffi.sdl-video" (emit/header-ns {:ns-prefix "sdl3.ffi"} "/x/SDL3/SDL_video.h")))
  (is (= "joltc.ffi" (emit/header-ns {:ns-prefix "joltc" :ns-names {"joltc.h" "joltc.ffi"}} "/x/joltc.h")))
  (is (= "sdl3/ffi/video.jolt" (emit/ns-file 'sdl3.ffi.video)))
  (is (= "my_lib/raw.jolt" (emit/ns-file 'my-lib.raw))))

(def ctx
  {:typedefs {} :system-typedefs {} :enums {}
   :records {"P" {:name "P" :kind :struct :complete? true :fields [{:name "x" :type "int"}]}}})

(def empty-parts {:constants {} :enums [] :callbacks {} :records [] :functions []})

(defn- render
  ([parts] (render parts #{}))
  ([parts blocking]
   (:source (emit/render-namespace {:ctx ctx :blocking blocking :header-file "x.h" :source-label "x 1.0"}
                                   'x.ffi (merge empty-parts parts)))))

(defn- def-value
  "The value a (def name ...) line in the source reads back as."
  [source name]
  (read-string (second (re-find (re-pattern (str "\\(def " name " (.*)\\)")) source))))

(deftest namespace-header
  (is (str/starts-with? (render {})
                        "(ns x.ffi\n  \"Generated by native-gen from x.h (x 1.0). Do not edit by hand.\"\n  (:require [jolt.ffi :as ffi]))")))

(deftest functions
  (let [f {:name "f" :ret "int" :params [{:name "a" :type "int"} {:name "s" :type "const char *"}] :variadic? false}]
    (is (str/includes? (render {:functions [f]}) ";; int f(int a, const char * s)\n(ffi/defcfn f \"f\" [:int :string] :int)"))
    (testing "a blocking call passes its strings as pointers"
      (let [out (render {:functions [f]} #{"f"})]
        (is (str/includes? out "(ffi/defcfn f \"f\" [:int :pointer] :int :blocking)"))
        (is (str/includes? out "ffi/with-c-string")))))
  (testing "a variadic function ends its argument vector with the bare marker"
    (let [out (render {:functions [{:name "lg" :ret "void" :params [{:name "fmt" :type "const char *"}] :variadic? true}]})]
      (is (str/includes? out "(ffi/defcfn lg \"lg\" [:string :&] :void)"))
      (is (str/includes? out ";; void lg(const char * fmt, ...)"))
      (is (str/includes? out ";; variadic:"))))
  (testing "a struct by value, in and out"
    (let [out (render {:functions [{:name "mk" :ret "struct P" :params [{:name "p" :type "struct P"}] :variadic? false}]})]
      (is (str/includes? out "(ffi/defcfn mk \"mk\" [[:by-value [:struct [[:x :int]]]]] [:by-value [:struct [[:x :int]]]])"))
      (is (str/includes? out "FIRST argument"))
      (is (str/includes? out "passed as pointers to the struct")))))

(deftest constants-and-enums
  (let [out (render {:constants {"A" {:type :int :value "3"}
                                 "B" {:type :uint :value "18446744073709551615"}
                                 "S" {:type :string :value "s\"q"}
                                 "D" {:type :double :value 1.5}
                                 "T" {:type :bool :value true}
                                 "N" {:type :int :value "-9223372036854775808"}}})]
    (is (str/includes? out "(def A 3)"))
    (is (str/includes? out "(def B 18446744073709551615N)"))
    (is (str/includes? out "(def N -9223372036854775808)"))
    (is (= "s\"q" (def-value out "S")))
    (is (= 1.5 (def-value out "D")))
    (is (true? (def-value out "T"))))
  (let [out (render {:enums [{:name "Mode" :constants [["A" 0] ["B" 5]]}]})]
    (is (str/includes? out "(def Mode {:A 0, :B 5})"))
    (is (str/includes? out "(def A 0)"))
    (is (str/includes? out "(def B 5)")))
  (testing "an enum the header never named has constants and no map"
    (let [out (render {:enums [{:name nil :constants [["LOOSE" 3]]}]})]
      (is (str/includes? out ";;; enums\n(def LOOSE 3)\n")))))

(deftest records-and-callbacks
  (let [out (render {:records [(get-in ctx [:records "P"])] :callbacks {"Cb" {:args [:pointer] :ret :void}}})]
    (is (str/includes? out "(def P-desc [:struct [[:x :int]]])"))
    (is (str/includes? out "(def P (ffi/layout [:struct [[:x :int]]]))"))
    (is (= {:args [:pointer] :ret :void} (def-value out "Cb")))))

(deftest name-collisions
  (testing "a constant that collides with a function, a record or an enum constant is reported, not emitted"
    (let [{:keys [source skipped]}
          (emit/render-namespace {:ctx ctx :blocking #{} :header-file "x.h"} 'x.ffi
                                 (merge empty-parts
                                        {:constants {"f" {:type :int :value "1"} "P-desc" {:type :int :value "2"}}
                                         :records [(get-in ctx [:records "P"])]
                                         :functions [{:name "f" :ret "void" :params [] :variadic? false}]}))]
      (is (= [["P-desc" "name already used"] ["f" "name already used"]] (sort skipped)))
      (is (not (str/includes? source "(def f 1)")))
      (is (str/includes? source "(ffi/defcfn f \"f\" [] :void)")))))
